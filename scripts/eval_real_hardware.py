"""Evaluate a trained FidelityNO checkpoint on real-hardware (Fake*V2)
data generated by ``gen_real_hardware_data.py``.

Outputs:
  results_prxq/real_hardware/<backend>_summary.csv
      one row per (backend, length) with MAE / pinball / CRPS / ECE / latency
  results_prxq/real_hardware/<backend>_predictions.npz
      raw quantiles + ground-truth for downstream plots
  results_prxq/real_hardware/headline.csv
      one row per (model, seed, backend) headline F_e MAE
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import numpy as np
import pandas as pd
import torch
from omegaconf import OmegaConf
from torch.utils.data import DataLoader, TensorDataset

from train import make_model, prediction_to_quantiles
from physics.fidelity import ef_to_avg


def pinball_np(q: np.ndarray, y: np.ndarray, levels) -> float:
    e = y[:, None] - q
    lev = np.asarray(levels)[None, :]
    return float(np.maximum(lev * e, (lev - 1) * e).mean())


def coverage_ece(q: np.ndarray, y: np.ndarray, levels) -> tuple[float, np.ndarray]:
    cov = (y[:, None] <= q).mean(0)
    return float(np.abs(cov - np.asarray(levels)).mean()), cov


def crps_from_quantiles(q: np.ndarray, y: np.ndarray, levels) -> float:
    return float(2 * pinball_np(q, y, levels))


def evaluate_checkpoint_on_split(ckpt_path: str, npz_path: str, device: str = "cpu") -> dict:
    ck = torch.load(ckpt_path, map_location=device, weights_only=False)
    cfg = OmegaConf.create(ck["cfg"])
    levels = list(cfg.model.quantiles)

    raw = np.load(npz_path, allow_pickle=True)
    input_dim = raw["x"].shape[-1]
    max_len = raw["x"].shape[1]
    model = make_model(cfg.model.name, input_dim, max_len, cfg)
    model.load_state_dict(ck["model"])
    model.to(device).eval()

    ds = TensorDataset(
        torch.tensor(raw["x"]).float(),
        torch.tensor(raw["mask"]).float(),
        torch.tensor(raw["y"]).float(),
        torch.tensor(raw["stats"]).float(),
    )
    preds, ys = [], []
    t0 = time.perf_counter()
    nseq = 0
    with torch.no_grad():
        for x, m, y, _stats in DataLoader(ds, batch_size=256):
            x = x.to(device); m = m.to(device)
            pred, _ = model(x, m)
            q = prediction_to_quantiles(pred, torch.tensor(levels, dtype=torch.float32, device=device))
            preds.append(q.cpu().numpy())
            ys.append(y.numpy())
            nseq += len(y)
    elapsed = time.perf_counter() - t0
    q = np.concatenate(preds)
    y = np.concatenate(ys)
    mean = q.mean(1)

    return {
        "model": cfg.model.name,
        "head_type": cfg.model.get("head_type", "quantile"),
        "seed": int(cfg.seed),
        "levels": levels,
        "quantiles": q,
        "ground_truth": y,
        "lengths": np.asarray(raw["length"]),
        "elapsed_s": elapsed,
        "nseq": nseq,
        "y_mean_truth": float(y.mean()),
        "y_std_truth": float(y.std()),
    }


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--ckpts", nargs="+", required=True,
                    help="Paths to checkpoint files. Can pass multiple seeds / models.")
    ap.add_argument("--data-root", default="data/real_hardware",
                    help="Root produced by gen_real_hardware_data.py.")
    ap.add_argument("--out-root", default="results_prxq/real_hardware")
    ap.add_argument("--backends", nargs="*", default=None,
                    help="Optional subset of backend dirs under data-root.")
    ap.add_argument("--device", default="cpu")
    args = ap.parse_args()

    out_root = Path(args.out_root)
    out_root.mkdir(parents=True, exist_ok=True)
    data_root = Path(args.data_root)

    if args.backends is None:
        backends = sorted(d.name for d in data_root.iterdir() if d.is_dir())
    else:
        backends = list(args.backends)

    headline_rows = []
    detail_rows = []
    for backend in backends:
        npz_path = data_root / backend / "real_hw_test.npz"
        if not npz_path.exists():
            print(f"[skip] {backend}: no real_hw_test.npz")
            continue
        for ckpt in args.ckpts:
            res = evaluate_checkpoint_on_split(ckpt, str(npz_path), device=args.device)
            q = res["quantiles"]; y = res["ground_truth"]; lens = res["lengths"]
            mean = q.mean(1)
            mae = float(np.abs(mean - y).mean())
            mae_avg = float(np.abs(np.array([ef_to_avg(m, 2) for m in mean]) - np.array([ef_to_avg(yi, 2) for yi in y])).mean())
            ece, cov = coverage_ece(q, y, res["levels"])
            crps = crps_from_quantiles(q, y, res["levels"])
            headline_rows.append({
                "backend": backend,
                "ckpt": Path(ckpt).name,
                "model": res["model"],
                "head_type": res["head_type"],
                "seed": res["seed"],
                "n_seq": res["nseq"],
                "y_mean_truth_F_e": res["y_mean_truth"],
                "y_std_truth_F_e": res["y_std_truth"],
                "y_mean_truth_F_avg": ef_to_avg(res["y_mean_truth"], 2),
                "mae_F_e": mae,
                "mae_F_avg": mae_avg,
                "ece": ece,
                "crps": crps,
                "latency_ms": 1000 * res["elapsed_s"] / max(res["nseq"], 1),
                "max_abs_err_F_e": float(np.abs(mean - y).max()),
            })
            for L in sorted(set(lens.tolist())):
                idx = lens == L
                if idx.sum() == 0:
                    continue
                detail_rows.append({
                    "backend": backend,
                    "ckpt": Path(ckpt).name,
                    "model": res["model"],
                    "seed": res["seed"],
                    "length": int(L),
                    "n": int(idx.sum()),
                    "mae_F_e": float(np.abs(mean[idx] - y[idx]).mean()),
                    "pinball": pinball_np(q[idx], y[idx], res["levels"]),
                    "crps": crps_from_quantiles(q[idx], y[idx], res["levels"]),
                    "ece": coverage_ece(q[idx], y[idx], res["levels"])[0],
                })

            preds_path = out_root / f"{backend}__{Path(ckpt).stem}_predictions.npz"
            np.savez_compressed(preds_path, quantiles=q, ground_truth=y, lengths=lens, levels=np.array(res["levels"]))

    headline_csv = out_root / "headline.csv"
    detail_csv = out_root / "by_length.csv"
    pd.DataFrame(headline_rows).to_csv(headline_csv, index=False)
    pd.DataFrame(detail_rows).to_csv(detail_csv, index=False)

    print(f"\n[saved] {headline_csv}")
    print(pd.DataFrame(headline_rows).to_string(index=False))
    print(f"\n[saved] {detail_csv}")


if __name__ == "__main__":
    main()
